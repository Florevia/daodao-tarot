/**
 * Inlines prompts/ and examples/gold into lib/prompt/bundle.generated.ts
 * so the serverless function does not read the markdown from disk.
 */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";

const root = process.cwd();

function walk(dir: string): string[] {
  const found: string[] = [];
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const full = join(dir, entry.name);
    if (entry.isDirectory()) found.push(...walk(full));
    else if (entry.name.endsWith(".md")) found.push(full);
  }
  return found.sort();
}

const files = Object.fromEntries(
  walk(join(root, "prompts")).map((full) => [relative(join(root, "prompts"), full).replaceAll("\\", "/"), readFileSync(full, "utf8")]),
);
const gold = JSON.parse(readFileSync(join(root, "examples/gold/readings.json"), "utf8"));

const out = `/* Generated by scripts/bundle-prompts.ts. Do not edit. */
export const promptFiles: Record<string, string> = ${JSON.stringify(files, null, 2)};

export type BundledGold = {
  id: string;
  spreadId: string;
  context: { status?: string; focus?: string; area?: string; mood?: string; theme?: string };
  question: string;
  overview: string;
  cards: { positionId: string; cardId: string; reversed: boolean; body: string }[];
  connection: string;
  conclusion: string;
};

export const goldReadings: BundledGold[] = ${JSON.stringify(gold, null, 2)};
`;

writeFileSync(join(root, "lib/prompt/bundle.generated.ts"), out);
console.log(`Bundled ${Object.keys(files).length} prompt files and ${gold.length} gold readings.`);
